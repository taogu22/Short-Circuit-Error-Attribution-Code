"""
Judges per-stage correctness on top of results already collected -- this
does NOT call the pipeline again, it reads what's already in
results/TAE_results_plain.csv (or results/two_stage_results_oracle_*.csv)
and grades each stage's output against ground truth.

This is the "LLM-judge" half of the "LLM-judge + manual spot-check"
methodology. After this runs, sample a handful of judgments per stage
(especially ones that surprise you) and read the raw description/rule
yourself -- don't treat this script's output as final without that.

Two things this script computes, depending on which CSV you point it at:

1) Run against results/TAE_results_plain.csv (the own/plain pipeline,
   all ~35 tasks): gives per_d, per_t, rea_d verdicts for every task.
   From this you can compute:
     - short-circuit M_i/M: walk per_d -> rea_d -> per_t -> rea_t in order
       for every task where plain_is_correct is False, attribute to the
       first WRONG stage (rea_t if the first three are all CORRECT but the
       task is still wrong).
     - e_perceptionstage_d / e_perceptionstage_t directly: perception's
       input (the raw image) is always correct by construction (Wang et
       al.'s own point), so there's no upstream corruption to correct for
       -- the plain pipeline's own per_d/per_t error rate already IS the
       intrinsic error rate e_i for these two stages. No oracle run
       needed for these two.

2) Run against results/two_stage_results_oracle_imagetext.csv (or
   _textonly.csv, the 10-task oracle pilot): set JUDGE_PER_D/JUDGE_PER_T
   to False (the descriptions there are oracle-generated, already
   verified accurate) and only judge rea_d, using that file's "rule"
   column. The resulting WRONG rate over the 10 oracle-pilot tasks is
   e_reasoningstage_d: does rule induction still fail even when perception
   is guaranteed correct?

e_reasoningstage_t is NOT covered here -- see NEXT_STEPS.md item 3, it
needs a further recursive-substitution experiment (oracle rule + oracle
test description fed alone into just the application step).
"""

