PER_JUDGE_PROMPT = """You are grading whether a natural-language description of an ARC puzzle grid is accurate.

True grid (ground truth, 0-indexed from top-left):
{grid}

Description to grade:
{description}

Color mapping: 0=black, 1=blue, 2=red, 3=green, 4=yellow, 5=grey, 6=fuchsia, 7=orange, 8=teal, 9=brown/maroon.

Judge whether the description is an ACCURATE account of the true grid -- correct object shapes, positions, colors, and counts. Minor omissions are fine; wrong shapes/positions/colors/counts are not.

Respond with ONLY a JSON object: {{"verdict": "CORRECT" or "WRONG", "reason": "one sentence"}}"""

REA_D_JUDGE_PROMPT = """You are grading whether an induced transformation rule correctly explains a set of demonstration examples in an ARC puzzle.

Demonstration examples (ground truth grids, 0-indexed from top-left):
{demos}

Proposed rule:
{rule}

Color mapping: 0=black, 1=blue, 2=red, 3=green, 4=yellow, 5=grey, 6=fuchsia, 7=orange, 8=teal, 9=brown/maroon.

Mentally apply the proposed rule to each demo input. Judge whether doing so reproduces that demo's true output, for EVERY demo pair shown above.

Respond with ONLY a JSON object: {{"verdict": "CORRECT" or "WRONG", "reason": "one sentence, naming which demo (if any) the rule fails on"}}"""


def clean_json_response(text):
    text = text.strip()
    text = text.removeprefix("```json").removeprefix("```")
    text = text.removesuffix("```")
    return text.strip()


def call_judge(prompt):
    response = client.chat.completions.create(
        model=MODEL,
        messages=[{"role": "user", "content": prompt}],
        reasoning_effort="medium",
    )
    text = response.choices[0].message.content
    parsed = json.loads(clean_json_response(text))
    return parsed["verdict"].strip().upper(), parsed["reason"]


def judge_description(description, true_grid):
    grid_str = "\n".join(str(row) for row in true_grid)
    prompt = PER_JUDGE_PROMPT.format(grid=grid_str, description=description)
    return call_judge(prompt)


def judge_rule(rule, demos):
    demo_str = "\n".join(
        f"Demo {i}: input={d['input']}, output={d['output']}" for i, d in enumerate(demos)
    )
    prompt = REA_D_JUDGE_PROMPT.format(demos=demo_str, rule=rule)
    return call_judge(prompt)


def load_own_descriptions(task_id):
    path = Path("images") / task_id / f"{task_id}_{DESCRIPTIONS_SUFFIX}.csv"
    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return {(row["train_id"], row["input/output"]): row["description"] for row in rows}


def load_results(path):
    """task_id -> row dict, from whichever results CSV we're judging."""
    with open(path, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return {row["task_id"]: row for row in rows if row.get("task_id")}


def main():
    with open("name_to_id.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    task_id_to_name = {row["task_id"]: row["original_filename"] for row in rows}

    result_rows = load_results(RESULTS_PATH)

    with open(OUTPUT_PATH, "w", newline="", encoding="utf-8") as out_f:
        writer = csv.writer(out_f)
        writer.writerow([
            "task_id", "per_d_verdict", "per_d_reason",
            "per_t_verdict", "per_t_reason",
            "rea_d_verdict", "rea_d_reason",
            "pipeline_is_correct",
        ])

        for task_id in TASK_IDS:
            print("==================")
            print(f"Judging {task_id}...")
            if task_id not in result_rows:
                print(f"  skipped: not in {RESULTS_PATH}")
                continue
            try:
                task_name = task_id_to_name[task_id]
                with open(Path("MiniARC") / (task_name + ".json")) as tf:
                    task = json.load(tf)

                own = load_own_descriptions(task_id) if (JUDGE_PER_D or JUDGE_PER_T) else {}

                per_d_verdict, per_d_reason = "", ""
                if JUDGE_PER_D:
                    per_d_verdict = "CORRECT"
                    per_d_reasons = []
                    for i, pair in enumerate(task["train"]):
                        for io_key, grid in [("input", pair["input"]), ("output", pair["output"])]:
                            v, r = judge_description(own[(str(i), io_key)], grid)
                            if v != "CORRECT":
                                per_d_verdict = "WRONG"
                            per_d_reasons.append(f"demo{i}.{io_key}: {v} ({r})")
                    per_d_reason = " | ".join(per_d_reasons)

                per_t_verdict, per_t_reason = "", ""
                if JUDGE_PER_T:
                    per_t_verdict, per_t_reason = judge_description(
                        own[("test", "input")], task["test"][0]["input"]
                    )

                rea_d_verdict, rea_d_reason = "", ""
                if JUDGE_REA_D:
                    rea_d_verdict, rea_d_reason = judge_rule(result_rows[task_id]["rule"], task["train"])

                writer.writerow([
                    task_id, per_d_verdict, per_d_reason,
                    per_t_verdict, per_t_reason,
                    rea_d_verdict, rea_d_reason,
                    result_rows[task_id]["is_correct"],
                ])
                out_f.flush()
                print(f"  per_d={per_d_verdict or 'n/a'}, per_t={per_t_verdict or 'n/a'}, rea_d={rea_d_verdict or 'n/a'}")

            except Exception as e:
                print(f"{task_id}: FAILED - {type(e).__name__}: {e}")
                writer.writerow([task_id, "ERROR", str(e), "", "", "", "", ""])
                out_f.flush()

    print("Judging completed. Results in", OUTPUT_PATH)


if __name__ == "__main__":
    main()
